"""Outline and outline review decision models."""

from typing import Literal
from pydantic import BaseModel, Field


class SectionPlan(BaseModel):
    """Specific editorial plan and evidence assignment for a single section."""

    heading: str = Field(..., description="Section title or heading")
    purpose: str = Field(..., description="Editorial objective: what argument or analysis this section advances")
    assigned_source_ids: list[int] = Field(default_factory=list, description="IDs of evidence sources assigned to this section")
    key_facts_to_integrate: list[str] = Field(default_factory=list, description="Concrete data points, findings, or examples to include")
    estimated_words: int = Field(default=120, description="Approximate word budget for this section")


class ContentOutline(BaseModel):
    """Structured outline generated by the Strategist."""

    title: str
    target_sections: list[str] = Field(default_factory=list)
    key_claims_to_cover: list[str] = Field(default_factory=list)
    source_ids_referenced: list[int] = Field(default_factory=list)
    estimated_word_count: int = 500
    angle_or_thesis: str = Field(default="", description="Core thesis or editorial perspective distinguishing this article")
    research_brief: str = Field(default="", description="Structured synthesis of facts, metrics, and tradeoffs from research")
    section_plans: list[SectionPlan] = Field(default_factory=list, description="Section-by-section evidence assignments")


class OutlineReviewDecision(BaseModel):
    """Structured decision produced by the Outline Review Agent."""

    decision: Literal["approve", "revise", "research_more"]
    rationale: str
    revision_feedback: list[str] = Field(default_factory=list)
    suggested_focus_areas: list[str] = Field(default_factory=list)
